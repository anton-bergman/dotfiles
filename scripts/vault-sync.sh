#!/usr/bin/env bash
set -euo pipefail

UID_VAL="${UID:-$(id -u)}"
DOTFILES_DIR="${DOTFILES_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
VAULT_RUNTIME_DIR="${XDG_RUNTIME_DIR:-${TMPDIR:-/tmp}}"
VAULT_RUNTIME_DIR="${VAULT_RUNTIME_DIR%/}"
ENV_FILE="${VAULT_RUNTIME_DIR}/vault-env-${UID_VAL}.zsh"

# Ensure Homebrew and Mise tool paths are available (crucial when invoked via tmux popup)
if [[ -f "/opt/homebrew/bin/brew" ]]; then
	eval "$(/opt/homebrew/bin/brew shellenv)"
fi
if [[ -f "$HOME/.local/bin/mise" ]]; then
	export PATH="$HOME/.local/bin:$PATH"
	eval "$("$HOME/.local/bin/mise" activate bash --shims 2>/dev/null || true)"
elif command -v mise >/dev/null 2>&1; then
	eval "$(mise activate bash --shims 2>/dev/null || true)"
fi

pause_on_error() {
	local msg="${1:-Vault sync failed.}"
	echo -e "\n\033[31m[ERROR]\033[0m $msg" >&2
	if [[ -t 0 ]]; then
		echo -e "\033[33mPress any key to close...\033[0m" >&2
		read -r -n 1 -s || true
	fi
	exit 1
}

# 1. Verify rbw and unlock if needed
if command -v rbw >/dev/null 2>&1; then
	if ! rbw unlocked >/dev/null 2>&1; then
		echo "Unlocking Bitwarden (rbw)..."
		rbw unlock || pause_on_error "Failed to unlock Bitwarden."
	fi
fi

# 2. Verify fnox
if ! command -v fnox >/dev/null 2>&1; then
	pause_on_error "fnox executable not found in PATH."
fi

# 3. Export secrets from fnox as JSON
echo "Resolving secrets via fnox..."
SECRETS_JSON="$(fnox export --format json 2>&1)" || pause_on_error "fnox export failed: $SECRETS_JSON"

# 4. Atomically write env file and set tmux global environment
python3 - "$SECRETS_JSON" "$ENV_FILE" <<'PYEOF'
import json
import os
import subprocess
import sys

raw_json = sys.argv[1]
target_file = sys.argv[2]
tmp_file = f"{target_file}.tmp.{os.getpid()}"

try:
    data = json.loads(raw_json)
    secrets = data.get("secrets", {})
except Exception as e:
    sys.exit(f"Failed to parse fnox output: {e}")

if not secrets:
    sys.exit("No secrets resolved from fnox.")

is_tmux = bool(os.environ.get("TMUX"))

lines = ["# Generated by vault-sync.sh - do not edit directly\n"]
for key, val in secrets.items():
    if val is None:
        continue
    # Escape single quotes for POSIX/zsh export
    escaped_val = str(val).replace("'", "'\"'\"'")
    lines.append(f"export {key}='{escaped_val}'\n")

    # Set in global tmux environment for all future windows/panes
    if is_tmux:
        subprocess.run(["tmux", "set-environment", "-g", key, str(val)], check=False)

# Write atomic file with 0600 permissions
with open(tmp_file, "w", encoding="utf-8") as f:
    f.writelines(lines)
os.chmod(tmp_file, 0o600)
os.replace(tmp_file, target_file)
PYEOF

# 5. Broadcast SIGUSR1 to all active zsh panes across tmux (excluding current process)
if [[ -n "${TMUX:-}" ]]; then
	tmux list-panes -a -F "#{pane_pid} #{pane_current_command}" |
		awk -v cur="$$" '$2 == "zsh" && $1 != cur {print $1}' |
		while read -r pid; do
			kill -USR1 "$pid" 2>/dev/null || true
		done
	tmux display-message -d 2500 "✓ Vault secrets synced to tmux & all active panes"
fi

# 6. If sourced in current shell, source the environment immediately
if [[ "${BASH_SOURCE[0]:-$0}" != "$0" ]]; then
	# shellcheck source=/dev/null
	source "$ENV_FILE"
fi

echo -e "\033[32m✓ Vault sync complete.\033[0m"
